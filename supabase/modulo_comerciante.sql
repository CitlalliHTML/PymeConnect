create table if not exists public.verificaciones (
  id          bigint generated by default as identity primary key,
  comercio_id bigint not null references public.comercios(id) on delete cascade,
  estado      text   not null default 'en_revision' check (estado in ('en_revision','aprobada','rechazada')),
  documentos  text[] not null default '{}',
  nota_admin  text,
  created_at  timestamptz not null default now()
);

-- 2) RLS --------------------------------------------------------------------
alter table public.comercios      enable row level security;
