-- comercios: el dueño ve/edita SOLO el suyo; el admin ve todo
drop policy if exists "dueño ve su comercio"    on public.comercios;
drop policy if exists "dueño crea su comercio"  on public.comercios;
drop policy if exists "dueño edita su comercio" on public.comercios;
drop policy if exists "admin ve comercios"      on public.comercios;
create policy "dueño ve su comercio"    on public.comercios for select using (propietario_id = auth.uid());
create policy "dueño crea su comercio"  on public.comercios for insert with check (propietario_id = auth.uid());
create policy "dueño edita su comercio" on public.comercios for update using (propietario_id = auth.uid()) with check (propietario_id = auth.uid());
create policy "admin ve comercios"      on public.comercios for select using (public.es_admin());

-- ⚠ CLAVE: el comerciante NO puede tocar `verificado` ni `propietario_id` (solo columnas permitidas)
revoke insert, update on public.comercios from authenticated;
grant  insert (propietario_id, nombre, categoria_id, descripcion, direccion, telefono, whatsapp, redes, foto_url, logo_url, latitud, longitud)
  on public.comercios to authenticated;
grant  update (nombre, categoria_id, descripcion, direccion, telefono, whatsapp, redes, foto_url, logo_url, latitud, longitud)
  on public.comercios to authenticated;

-- productos: público ve solo activos; el dueño gestiona los suyos
drop policy if exists "público ve productos activos" on public.productos;
drop policy if exists "dueño gestiona sus productos" on public.productos;
create policy "público ve productos activos" on public.productos for select using (activo);
create policy "dueño gestiona sus productos" on public.productos for all
  using      (exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()))
  with check (exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()));

-- horarios: público lee; el dueño gestiona los suyos
drop policy if exists "público ve horarios"          on public.horarios;
drop policy if exists "dueño gestiona sus horarios"  on public.horarios;
create policy "público ve horarios" on public.horarios for select using (true);
create policy "dueño gestiona sus horarios" on public.horarios for all
  using      (exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()))
  with check (exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()));

-- verificaciones: el dueño crea (solo 'en_revision') y lee las suyas; solo el admin resuelve
drop policy if exists "dueño ve sus verificaciones"   on public.verificaciones;
drop policy if exists "dueño solicita verificación"   on public.verificaciones;
drop policy if exists "admin ve verificaciones"       on public.verificaciones;
create policy "dueño ve sus verificaciones" on public.verificaciones for select
  using (exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()));
create policy "dueño solicita verificación" on public.verificaciones for insert
  with check (estado = 'en_revision' and nota_admin is null
              and exists (select 1 from public.comercios c where c.id = comercio_id and c.propietario_id = auth.uid()));
create policy "admin ve verificaciones" on public.verificaciones for select using (public.es_admin());

-- Resolver una verificación: SOLO administradores (security definer + comprobación de rol)
create or replace function public.resolver_verificacion(p_id bigint, p_estado text, p_nota text default null)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.es_admin() then raise exception 'No autorizado'; end if;
  if p_estado not in ('aprobada','rechazada') then raise exception 'Estado inválido'; end if;
  update public.verificaciones set estado = p_estado, nota_admin = p_nota where id = p_id;
  update public.comercios set verificado = (p_estado = 'aprobada')
   where id = (select comercio_id from public.verificaciones where id = p_id);
end $$;
revoke all on function public.resolver_verificacion(bigint, text, text) from public, anon;
grant execute on function public.resolver_verificacion(bigint, text, text) to authenticated;

