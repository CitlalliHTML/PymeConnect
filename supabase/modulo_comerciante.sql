-- 4) Registro seguro ------------------------------------------------------------
-- (a) Todo registro desde la web es 'comerciante'. El cliente NO puede elegir rol (signUp solo escribe user_metadata).
--     Los administradores se crean a mano (ver al final).
create or replace function public.asignar_rol_al_registrarse() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(new.raw_app_meta_data ->> 'rol', '') = '' then
    new.raw_app_meta_data := coalesce(new.raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('rol', 'comerciante');
  end if;
  return new;
end $$;
drop trigger if exists trg_asignar_rol on auth.users;
create trigger trg_asignar_rol before insert on auth.users for each row execute function public.asignar_rol_al_registrarse();

-- (b) Crea el negocio con los datos del formulario de registro (se validan y recortan aquí, no solo en el navegador)
create or replace function public.crear_comercio_al_registrarse() returns trigger
language plpgsql security definer set search_path = '' as $$
declare m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  if new.raw_app_meta_data ->> 'rol' = 'comerciante' then
    insert into public.comercios (propietario_id, nombre, telefono, direccion, categoria_id)
    values (
      new.id,
      left(nullif(trim(m ->> 'negocio'), ''), 80),
      left(regexp_replace(coalesce(m ->> 'telefono', ''), '\D', '', 'g'), 15),
      left(nullif(trim(m ->> 'direccion'), ''), 160),
      case when (m ->> 'categoria_id') ~ '^\d{1,9}$' then (m ->> 'categoria_id')::bigint end
    ) on conflict do nothing;
  end if;
  return new;
end $$;
drop trigger if exists trg_crear_comercio on auth.users;
create trigger trg_crear_comercio after insert on auth.users for each row execute function public.crear_comercio_al_registrarse();
-- Nota: `nombre` es NOT NULL; si el registro llega sin negocio, el insert falla y el registro se rechaza (es lo deseado).

