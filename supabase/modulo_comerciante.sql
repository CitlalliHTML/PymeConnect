-- 0) Helper: ¿el token pertenece a un administrador? (el rol vive en app_metadata, que el cliente NO puede editar)
create or replace function public.es_admin() returns boolean
language sql stable as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'rol', '') = 'administrador'
$$;

-- 1) Columnas ---------------------------------------------------------------
